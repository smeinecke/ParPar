#[cfg(test)]
mod tests {
    #[test]
    fn asm_matches_scalar() {
        let mut data = vec![0u8; 64 * 37];
        for (i, b) in data.iter_mut().enumerate() {
            *b = (i as u32).wrapping_mul(2654435761) as u8;
        }
        let mut s_asm = [0x67452301u32, 0xefcdab89, 0x98badcfe, 0x10325476];
        let mut s_ref = s_asm;
        for (n, blk) in data.chunks_exact(64).enumerate() {
            super::md5_block_asm(&mut s_asm, blk);
            crate::md5::md5_process_block(&mut s_ref, blk);
            if s_asm != s_ref {
                eprintln!("blk {n}: asm {:08x?} ref {:08x?}", s_asm, s_ref);
                break;
            }
        }
        assert_eq!(s_asm, s_ref);
    }
}
